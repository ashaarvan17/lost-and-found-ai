import { useState } from "react";
import { Sparkles, Search, RefreshCw } from "lucide-react";
import MatchCard from "../components/MatchCard";
import "../styles/pages.css";

const demoMatches = [
  {
    id: 101,
    lostItem: {
      title: "Black Leather Wallet",
      category: "Accessories",
      location: "College Library",
    },
    foundItem: {
      title: "Black Wallet",
      category: "Accessories",
      location: "Library Entrance",
    },
    similarityScore: 87,
    matchingAttributes: [
      "Similar color",
      "Same category",
      "Nearby locations",
    ],
  },
  {
    id: 102,
    lostItem: {
      title: "Blue Water Bottle",
      category: "Personal Items",
      location: "Cafeteria",
    },
    foundItem: {
      title: "Blue Sports Bottle",
      category: "Personal Items",
      location: "Student Lounge",
    },
    similarityScore: 76,
    matchingAttributes: [
      "Similar color",
      "Similar description",
    ],
  },
];

export default function Matches() {
  const [search, setSearch] = useState("");

  const filteredMatches = demoMatches.filter((match) => {
    const query = search.trim().toLowerCase();

    return [
      match.lostItem.title,
      match.foundItem.title,
      ...match.matchingAttributes,
    ].some((value) => value.toLowerCase().includes(query));
  });

  return (
    <div className="page-container">
      <div className="page-heading-row">
        <div>
          <span className="eyebrow">INTELLIGENT DISCOVERY</span>
          <h1>AI Potential Matches</h1>
          <p>
            Review lost and found reports that may describe the same item.
          </p>
        </div>

        <span className="ai-pill">
          <Sparkles size={15} /> AI-Assisted
        </span>
      </div>

      <div className="ai-info-banner">
        <div className="ai-banner-icon"><Sparkles size={22} /></div>
        <div>
          <h3>How matching works</h3>
          <p>
            AI compares available information such as item descriptions,
            categories, colors, and locations to rank potential matches.
            Similarity scores are not proof of ownership.
          </p>
        </div>
      </div>

      <div className="browse-toolbar">
        <div className="browse-search">
          <Search size={19} />
          <input
            type="search"
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            placeholder="Search potential matches..."
            aria-label="Search potential matches"
          />
        </div>

        <button
          type="button"
          className="button button-secondary"
          onClick={() => setSearch("")}
        >
          <RefreshCw size={16} /> Reset Search
        </button>
      </div>

      <div className="match-list">
        {filteredMatches.length > 0 ? (
          filteredMatches.map((match) => (
            <MatchCard key={match.id} match={match} />
          ))
        ) : (
          <div className="empty-state">
            <div className="empty-state-icon"><Sparkles size={30} /></div>
            <h3>No matching reports found</h3>
            <p>Try a different search term.</p>
          </div>
        )}
      </div>

      <p className="demo-notice">
        These are sample matches. Real results will be generated by the
        Python AI service and retrieved through the backend API.
      </p>
    </div>
  );
}